// Pattern Break Watchlist data — chart patterns being tracked per stock.
// Percentages in the UI are measured from `price` (the close on `priceDate`),
// not from the stock file's `currentPrice`.
//
// direction: "down" | "up" | "both" ("both" = no break yet; uses breakUp/breakDown/goalUp/goalDown)
// stage:     "forming" | "signal" | "confirmed" | "target" | "failed" | "update"
//            "update" = needs updating: a pending setup closed past one of its limits;
//            prevStage / updateDate / updateNote record what it was, when, and what broke
//            (set by pattern_watchlist.py; stageDate keeps the date of the previous stage).

export type PatternDirection = 'up' | 'down' | 'both';
export type PatternStage = 'forming' | 'signal' | 'confirmed' | 'target' | 'failed' | 'update';
export type PatternTimeframe = 'daily' | 'weekly' | 'monthly';

// Optional trendline anchors for the chart: [date 'YYYY-MM-DD', price] pairs.
export type PatternLine = { from: [string, number]; to: [string, number] };

export interface PatternAltSetup {
  pattern?: string;
  timeframe: PatternTimeframe;
  flag?: string;
  direction: PatternDirection;
  stage: PatternStage;
  stageDate?: string;
  prevStage?: PatternStage;
  updateDate?: string;
  updateNote?: string;
  signal?: number;
  confirm?: number;
  invalidation?: number;
  target?: number;
  breakUp?: number;
  breakDown?: number;
  goalUp?: number;
  goalDown?: number;
  failRule?: string;
  note?: string;
  lines?: PatternLine[];
}

export interface PatternHistoryEntry {
  pattern: string;
  timeframe: PatternTimeframe;
  direction: 'up' | 'down';
  stage: PatternStage;
  stageDate: string;
  confirm: number;
  invalidation: number;
  target: number;
  note?: string;
}

export interface PatternStock {
  ticker: string;
  name: string;
  auto?: boolean;              // auto-detected by pattern_detect.py: red dot until checked by hand
  pattern: string;
  timeframe: PatternTimeframe;
  flag?: string;
  tag?: string;
  direction: PatternDirection;
  stage: PatternStage;
  stageDate?: string;
  prevStage?: PatternStage;
  updateDate?: string;
  updateNote?: string;
  price: number;
  priceDate: string;
  signal?: number;
  confirm?: number;
  invalidation?: number;
  target?: number;
  breakUp?: number;
  breakDown?: number;
  goalUp?: number;
  goalDown?: number;
  signalRule?: string;
  confirmRule?: string;
  failRule?: string;
  note?: string;
  lines?: PatternLine[];
  keyLevel?: { price: number; text: string };
  alt?: PatternAltSetup;
  history?: PatternHistoryEntry[];
}

